// pièces gagnées : tout le montant en cas de victoire, la moitié si égalité, un cinquième sinon
export function rewardFor(base, result) {
  if (result === 'win') return base;
  if (result === 'draw') return Math.round(base / 2);
  return Math.round(base / 5);
}
